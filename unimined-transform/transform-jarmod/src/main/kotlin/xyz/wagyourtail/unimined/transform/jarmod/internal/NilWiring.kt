package xyz.wagyourtail.unimined.transform.jarmod.internal

import org.gradle.api.Action
import org.gradle.api.Project
import org.gradle.api.tasks.SourceSet
import org.gradle.api.tasks.SourceSetContainer
import org.gradle.jvm.tasks.Jar
import xyz.wagyourtail.unimined.api.spec.Side
import xyz.wagyourtail.unimined.api.util.afterDslEval
import xyz.wagyourtail.unimined.minecraft.MinecraftEnvironment
import xyz.wagyourtail.unimined.minecraft.MinecraftExtension
import xyz.wagyourtail.unimined.minecraft.ModGroupSpec
import xyz.wagyourtail.unimined.mod.ModExtension
import xyz.wagyourtail.unimined.remap.RemapExtension
import xyz.wagyourtail.unimined.remapper.uml.nil.NilMappingsScanTask
import xyz.wagyourtail.unimined.transform.TransformExtension

/**
 * NilLoader env wiring — nilloader is a pure javaagent
 * (`Premain-Class: nilloader.NilAgent`): no jar merge, no transformer
 * registry, no launchwrapper. The same `com.unascribed:nilloader`
 * artifact serves both the compile classpath (nilmods compile against
 * `nilloader.api` + the mini-transformer classes) and the runtime
 * `-javaagent` entry, so a detached non-transitive configuration
 * resolves the bare jar for run configs while `modImplementation`
 * carries the normal dep.
 *
 * No production mapping hop: the game runs the official-named jar and
 * shipped nilmods re-obfuscate to `official` like jarmod — the
 * descriptor's `prodNamespace` covers it.
 *
 * `META-INF/nil/mappings.json` is generated by [NilMappingsScanTask]:
 * a tracked scan over the compiled mod classes emits the dev→official
 * references NIL resolves at runtime (`@Patch` targets, `remap*` args,
 * bytecode refs for ship-named mode) plus the widen set, injected into
 * the jar copy spec so it rides both the plain jar (identity/ship-named
 * mode) and the remapped jar (ship-official — `remapJar` mirrors the
 * jar's root spec). Mods patch the runtime through those mappings, so
 * class-name `ldc` rewriting must stay out of the mod-artifacts step —
 * rewriting owner/desc literals to the target namespace while member
 * names stay dev-named desyncs the runtime lookups.
 */
internal object NilWiring {

    fun wire(project: Project, environment: MinecraftEnvironment) {
        // nilmod is a client-side ecosystem (agent on the client main
        // class) — default only; a server env can still opt in
        environment.side.convention(Side.CLIENT)
        val envId = environment.environmentId
        val loaderVersion = environment.spec().loader?.version

        val nilAgent = project.configurations.maybeCreate(
            if (envId == "main") "nilAgent" else
                "nilAgent${envId.replaceFirstChar { it.uppercaseChar() }}"
        ).apply {
            isCanBeConsumed = false
            isTransitive = false
        }
        loaderVersion?.let { v ->
            project.dependencies.add(
                environment.modImplementationConfigurationName,
                "com.unascribed:nilloader:$v"
            )
            project.dependencies.add(
                nilAgent.name,
                "com.unascribed:nilloader:$v"
            )
        }

        // Execution-lazy agent argument. `runMutators` snapshots into the
        // configuration cache at STORE time, so resolving `nilAgent` there
        // performs dependency resolution during configuration. The
        // run-task contribution channel stores this provider verbatim and
        // queries it when the launch command assembles at execution.
        // `Configuration.elements` keeps the artifact resolution lazy and
        // configuration-cache-serializable; the nilAgent configuration is
        // non-transitive and should contain exactly the nilloader jar.
        val nilAgentArg = nilAgent.elements.map { elements ->
            val agents = elements.map { it.asFile }
            require(agents.size == 1) {
                "nilAgent for environment '$envId' must resolve to exactly " +
                    "one nilloader jar, got ${agents.size}: $agents"
            }
            "-javaagent:${agents.single().absolutePath}"
        }
        project.extensions.getByType(TransformExtension::class.java)
            .sourceSet(envId).runTaskContributions += Action { context ->
                context.lazyJvmArg(nilAgentArg)
            }

        wireNilMappings(project, environment)
    }

    /**
     * Select the `mods { }` group describing this environment's own
     * logical mod. Group names are mod ids by contract; the env's own
     * output is the same logical mod, so only the same-named group may
     * be folded into the nilmod jar. With no declared `mod.id`, a
     * single group is unambiguous and is used; several groups are not,
     * since folding every sibling mod into one jar would be wrong.
     */
    private fun logicalModGroup(
        project: Project,
        environment: MinecraftEnvironment
    ): ModGroupSpec? {
        val groups = environment.effectiveModGroups()
        if (groups.isEmpty()) return null
        val modId = project.extensions.findByType(ModExtension::class.java)
            ?.id?.orNull
        if (modId != null) {
            return groups.firstOrNull { it.name == modId }.also {
                if (it == null) project.logger.info(
                    "[Unimined] nil env '${environment.environmentId}' — " +
                        "no mods group named '$modId'; scanning/packaging " +
                        "the env's own output only"
                )
            }
        }
        if (groups.size == 1) return groups.single()
        project.logger.info(
            "[Unimined] nil env '${environment.environmentId}' — several " +
                "mods groups exist (${groups.joinToString { it.name }}) and " +
                "mod.id is unset; scanning/packaging the env's own output only"
        )
        return null
    }

    private fun extraGroupSourceSets(
        own: SourceSet,
        group: ModGroupSpec?
    ): List<SourceSet> = group?.sourceSets.orEmpty().filter { it != own }

    /** Register the mappings scan + jar injection. */
    private fun wireNilMappings(project: Project, environment: MinecraftEnvironment) {
        val envId = environment.environmentId
        val remap = project.extensions.getByType(RemapExtension::class.java)
        val minecraft = project.extensions.getByType(MinecraftExtension::class.java)

        // runtime string lookups key on dev-namespace owners — keep ldc
        // literals in the compile namespace (conventions only touch the
        // auto-appended default step; explicit modArtifacts {} blocks
        // own their behavior)
        remap.sourceSet(envId).modArtifactsConventions.add(Action { spec ->
            spec.disableClassNameLdcRemap()
        })

        project.afterDslEval { p ->
            val cap = envId.replaceFirstChar { it.uppercaseChar() }
            val scanTaskName = if (envId == "main") "scanNilMappings" else "scan${cap}NilMappings"
            val sourceSets = p.extensions.getByType(SourceSetContainer::class.java)
            val sourceSet = sourceSets.findByName(envId) ?: run {
                p.logger.info("[Unimined] nil env '$envId' has no matching source set — skipping mappings scan wiring")
                return@afterDslEval
            }
            val logicalGroup = logicalModGroup(p, environment)
            val groupedSourceSets = extraGroupSourceSets(sourceSet, logicalGroup)

            val devNamespace = minecraft.devNamespace(envId)
            // nil's runtime namespace is always official — the scan
            // bundle is independent of ship-mode (the json content is
            // identical either way). Registered outside the scan task's
            // configuration action — nested task registration during
            // task creation is an illegal container mutation
            val scanBundle = minecraft.mappingBundle(
                envId, "nil-mappings-scan", devNamespace,
                p.provider { "official" }
            )
            val scanTask = p.tasks.register(scanTaskName, NilMappingsScanTask::class.java) { t ->
                t.group = "unimined"
                t.description = "Scans the '$envId' classes and generates META-INF/nil/mappings.json"
                // The env jar is the runtime discovery unit. The same-named
                // mods{} group is the same logical mod on nil as well —
                // particularly shared-code `main` carrying the hand-written
                // or generated *.nilmod.css resource. Scan exactly the leaf
                // class outputs that jar embedding adds below; recursive
                // combineWith output is intentionally not expanded here
                // because composing jar packaging back into scan inputs
                // reintroduces a provider dependency cycle. Raw outputs from
                // a different era/namespace must be pre-remapped by the
                // build; mods{} has no namespace-hop channel, so scanning
                // them as this env's namespace would emit wrong rows.
                t.classDirs.from(sourceSet.output.classesDirs)
                groupedSourceSets.forEach { t.classDirs.from(it.output.classesDirs) }
                t.scanClasspath.from(sourceSet.compileClasspath)
                t.scanClasspath.from(sourceSet.output.classesDirs)
                // Access truth must come from the pristine source-namespace
                // product. The dev artifact may already have access widening
                // applied, which would under-report nil's runtime widen set.
                t.accessTruthJars.from(
                    p.configurations.named(environment.minecraftRawViewName)
                )
                t.devNamespace.set(devNamespace)
                t.defaultBundle.set(scanBundle)
                t.targetNamespaces.put("default", p.provider { "official" })
                t.outputFile.set(
                    p.layout.buildDirectory.file("nilMappings/$envId/mappings.json")
                )
            }

            // inject into the jar copy spec — `remapJar` mirrors the
            // jar's root spec lazily, so the file rides into both the
            // plain jar (identity/ship-named) and the remapped artifact
            (p.tasks.findByName(sourceSet.jarTaskName) as? Jar)?.let { jar ->
                // NilLoader discovers jars, not exploded classpath entries.
                // The same-named mods{} group is therefore embedded in the
                // discovery jar as well as scanned: without this a shared
                // `main` resource such as `omnilook.nilmod.css` is visible
                // to Java but invisible to the agent's JarFile scan.
                groupedSourceSets.forEach { jar.from(it.output) }
                jar.from(scanTask.flatMap { it.outputFile }) {
                    it.into("META-INF/nil")
                }
            } ?: p.logger.info(
                "[Unimined] source set '$envId' has no jar task — nil mappings scan registered but not injected"
            )
        }
    }
}
