package xyz.wagyourtail.unimined.adapter.patchbase

import groovy.lang.Closure
import groovy.lang.DelegatesTo
import org.gradle.api.Action
import org.gradle.api.Project
import org.gradle.api.artifacts.Configuration
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.jvm.tasks.Jar
import xyz.wagyourtail.patchbase.gradle.tasks.CreateClassPatchTask
import xyz.wagyourtail.patchbase.gradle.tasks.CreateSourcePatchTask
import xyz.wagyourtail.unimined.api.util.afterDslEval
import xyz.wagyourtail.unimined.api.util.delegatingTo
import xyz.wagyourtail.unimined.api.util.failProblem
import xyz.wagyourtail.unimined.api.util.registerDeprecatedTaskAlias
import xyz.wagyourtail.unimined.minecraft.MinecraftEnvironment
import xyz.wagyourtail.unimined.adapter.patchbase.internal.RecompileMcWiring
import xyz.wagyourtail.unimined.adapter.patchbase.task.ApplySourcePatchesTask

/**
 * Per-env `patchBase` DSL object — registered as the `patchBase`
 * extension on each environment by the adapter plugin.
 *
 * ```
 * sourceSet("main") {
 *     patchBase("my.patches:base-patch:1.0@zip") // consume a patchset
 *     patchBaseCreator()                        // author a patchset
 * }
 * ```
 */
abstract class PatchBaseEnvExtension(
    private val project: Project,
    private val env: MinecraftEnvironment,
    private val configuration: Configuration
) {

    private val sfx = env.environmentId.replaceFirstChar { it.uppercase() }
    private val taskSfx = if (env.environmentId == "main") "" else sfx
    private val patchDir = if (env.environmentId == "main")
        "patches" else "patches/${env.environmentId}"
    private val srcDir = if (env.environmentId == "main")
        "src/main/java" else "src/${env.environmentId}/java"

    /** Add a patch jar dependency — applied to this env's MC jar
     *  pre-remap (prod namespace). Consume side: declare a patchset
     *  dependency and its `.bdiff` set lands on the dev + compile
     *  classpaths via the env artifact. */
    fun patchBase(notation: Any) {
        project.dependencies.add(configuration.name, notation)
    }

    /**
     * Knobs for [patchBaseCreator] — the mache/git-style text-patch
     * loop layout. Defaults follow the reference workflow: the
     * git-tracked unified-diff set in `patches/` (per-env
     * `patches/<env>` when not `main`) and the generated,
     * edit-in-place patched sources in `src/<env>/java`.
     *
     * `applySourcePatch` regenerates the whole [sourceDir] tree from
     * [patchDir] on every run — a patchbase project keeps ONLY
     * patch-materialized files there; mix in hand-written sources and
     * they are deleted on the next apply. Point [sourceDir] at a
     * dedicated tree (or use a dedicated env) when the project also
     * carries normal sources.
     */
    abstract class PatchBaseCreatorSpec {
        /** Directory holding the git-tracked patch set — `*.patch`
         *  unified diffs keyed to the decompiled tree, plus verbatim
         *  `*.java` for net-new files. Convention: `patches/`
         *  (`patches/<env>` for non-main envs). */
        abstract val patchDir: DirectoryProperty

        /** Generated patched-source tree — where `applySourcePatch`
         *  materializes patch-covered files and `createSourcePatch`
         *  reads them back from. Wiped+regenerated by both tasks, so
         *  treat it as the patch overlay's checkout, not a normal
         *  source dir. Convention: `src/<env>/java`. */
        abstract val sourceDir: DirectoryProperty

        /** Context lines emitted into generated diffs.
         *  Convention: `3`. */
        abstract val diffContextSize: Property<Int>

        /** Strip leading whitespace when diffing (matches PatchBase's
         *  standalone extension default). Convention: `true`. */
        abstract val trimWhitespace: Property<Boolean>

        /** Class-patch entry format for `createClassPatch` —
         *  `binpatch` (forge/neoforge standard record) or `bdiff`
         *  (PatchBase's checksum+gdiff unit). Convention:
         *  `"binpatch"`. */
        abstract val patchFormat: Property<String>
    }

    /**
     * Authoring side — wires the patch-set tasks against this env's
     * handles (the mache loop: apply → edit → rebuild → ship):
     *
     * - `apply<Env>SourcePatch` — decompiled env sources + `patches/`
     *   `.patch` set → writes ONLY the patch-covered files into
     *   `src/<env>/java` (gitignore it — it's generated material).
     *   Compile + JarModAgent's priority classpath then override the
     *   stock classes at dev runtime.
     * - `create<Env>SourcePatch` — diffs `src/<env>/java` back into
     *   `patches/` (the git-tracked repo content).
     * - `create<Env>ClassPatch` — diffs the env's prod jar against its
     *   pre-remap base, producing the shippable `.bdiff` patch jar
     *   (checksums bind to the raw base — the same artifact consumers'
     *   `patchBase()` dep applies to).
     * - `recompile<Env>Mc` — recompiles the patched overlay against
     *   the env's dev jar and merges the classes over it, producing a
     *   full dev-namespace Minecraft jar (the FG-era `recompMc`
     *   analog; the `recompile<Env>McClasses` javac half runs first).
     *
     * The bare `main` forms keep the `applySourcePatch`/
     * `createSourcePatch`/`createClassPatch`/`recompileMc` names; the
     * pre-convention `<verb><Noun><Env>` names register deprecated
     * aliases for non-main envs.
     *
     * Task registration is deferred to post-DSL (`afterDslEval`) —
     * `gen<Env>Sources` and the raw-artifact view only exist once the
     * source/transform wiring has run — and no-ops cleanly when
     * `patches/` resp. `src/<env>/java` don't exist yet.
     */
    fun patchBaseCreator() = patchBaseCreator(Action {})

    /** Kotlin DSL form of [patchBaseCreator] with spec overrides. */
    fun patchBaseCreator(action: Action<PatchBaseCreatorSpec>) {
        val spec = project.objects.newInstance(PatchBaseCreatorSpec::class.java)
        spec.patchDir.convention(project.layout.projectDirectory.dir(patchDir))
        spec.sourceDir.convention(project.layout.projectDirectory.dir(srcDir))
        spec.diffContextSize.convention(3)
        spec.trimWhitespace.convention(true)
        spec.patchFormat.convention("binpatch")
        action.execute(spec)

        val envId = env.environmentId
        val genSourcesName =
            if (envId == "main") "genSources" else "gen${sfx}Sources"

        // gen<Env>Sources registers in the source plugin's own
        // afterDslEval (declared at env binding, ahead of this call),
        // so by the time this hook runs the task — and the
        // minecraftRaw view created eagerly at binding — both exist
        project.afterDslEval {
            if (!project.tasks.names.contains(genSourcesName)) {
                project.failProblem(
                    "patchbase/gen-sources-missing",
                    "unimined: patchBaseCreator() needs the " +
                        "'$genSourcesName' task",
                    "apply 'xyz.wagyourtail.unimined.source' (part of " +
                        "the xyz.wagyourtail.unimined frontend) or " +
                        "register a decompiled-sources task under " +
                        "that name"
                )
            }
            val genSources = project.tasks.named(genSourcesName)

            // resolved once here so the onlyIf specs capture plain
            // serializable Files, not the decorated spec object
            val patchDirFile = spec.patchDir.get().asFile
            val sourceDirFile = spec.sourceDir.get().asFile

            // verb<Env>Noun naming: `apply<Fabric>SourcePatch`; the
            // pre-convention `applySourcePatch<Env>` names stay as
            // deprecated aliases (main forms coincide — bare names)
            val applyPatch = project.tasks.register(
                "apply${taskSfx}SourcePatch",
                ApplySourcePatchesTask::class.java) {
                it.group = "patchbase"
                it.description = "Applies '${patchDirFile.toRelativeString(project.projectDir)}' " +
                    "onto the '$envId' decompiled sources, writing the " +
                    "patch-covered files to " +
                    "'${sourceDirFile.toRelativeString(project.projectDir)}'"
                it.patchDir.set(patchDirFile)
                it.outputDir.set(sourceDirFile)
                it.sources.set(project.files(genSources))
                // a fresh checkout has no patches/ yet — nothing to
                // apply (and regenerating would wipe the overlay)
                it.onlyIf("patch dir exists") { patchDirFile.exists() }
            }
            val createSource = project.tasks.register(
                "create${taskSfx}SourcePatch",
                CreateSourcePatchTask::class.java) {
                it.group = "patchbase"
                it.description = "Diffs " +
                    "'${sourceDirFile.toRelativeString(project.projectDir)}' " +
                    "against the '$envId' decompiled sources back into " +
                    "'${patchDirFile.toRelativeString(project.projectDir)}'"
                it.sourceDir.set(sourceDirFile)
                it.outputDir.set(patchDirFile)
                it.sources.set(project.files(genSources))
                it.trimWhitespace.set(spec.trimWhitespace)
                it.diffContextSize.set(spec.diffContextSize)
                it.onlyIf("patched source dir exists") { sourceDirFile.exists() }
            }
            if (envId != "main") {
                project.registerDeprecatedTaskAlias(
                    "applySourcePatch$sfx", applyPatch)
                project.registerDeprecatedTaskAlias(
                    "createSourcePatch$sfx", createSource)
            }

            // prod artifact: remap<Env>Jar when remap runs, else the
            // env's own jar; resolved lazily so either registration
            // order wins
            val prodJar = project.provider {
                sequenceOf("remap${taskSfx}Jar",
                    "remap${sfx}Jar",
                    if (envId == "main") "jar" else "${envId}Jar")
                    .distinct()
                    .mapNotNull { n -> project.tasks.findByName(n) }
                    .firstOrNull()
                    ?: project.failProblem("patchbase/prod-jar",
                        "unimined: no prod jar task for env '$envId'")
            }.flatMap { (it as Jar).archiveFile }

            val createClass = project.tasks.register(
                "create${taskSfx}ClassPatch",
                CreateClassPatchTask::class.java) {
                it.group = "patchbase"
                it.description = "Diffs the '$envId' production jar " +
                    "against its pre-remap base into a shippable " +
                    "binpatch/bdiff patch jar"
                it.inputFile.set(prodJar)
                it.patchFormat.set(spec.patchFormat)
                it.classpath.set(project.files(
                    project.configurations.named(env.minecraftRawViewName)))
                it.archiveClassifier.set(
                    if (envId == "main") "patch" else "patch-$envId")
            }
            if (envId != "main") {
                project.registerDeprecatedTaskAlias(
                    "createClassPatch$sfx", createClass)
            }

            RecompileMcWiring.wire(
                project, env, spec, taskSfx, sourceDirFile)
        }
    }

    /** Groovy DSL form of [patchBaseCreator]. */
    fun patchBaseCreator(
        @DelegatesTo(value = PatchBaseCreatorSpec::class,
            strategy = Closure.DELEGATE_FIRST)
        action: Closure<*>
    ) = patchBaseCreator(Action { action.delegatingTo(it) })

}
