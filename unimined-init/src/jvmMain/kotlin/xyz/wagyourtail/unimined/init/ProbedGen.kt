package xyz.wagyourtail.unimined.init

/** Build-time version probe — resolves every known probe axis and
 *  rewrites the committed `ProbedVersions.kt` so binaries ship an
 *  offline cache of supported versions. Run
 *  `./gradlew :unimined-init:genProbedVersions` before releases;
 *  dead mappings pick up surprise updates on rebuild. */
fun main(args: Array<String>) {
    val out = args[0]
    val r = VersionResolver()
    val p = linkedMapOf<String, List<String>>()
    fun probeList(key: String, block: () -> List<String>) {
        p[key] = runCatching(block).getOrDefault(emptyList())
    }
    probeList("@mc") { listOf(r.latestMinecraft()) }
    probeList("@plugin") { listOf(r.latestPlugin()) }
    for (loader in listOf("fabric", "quilt", "forge", "neoforge",
        "bta-babric", "foxloader", "stationapi", "osl", "bta", "reindev"))
        probeList(loader) { r.loaderVersions(loader, "1.20.1") }
    probeList("yarn:1.20.1") { r.loaderVersions("yarn", "1.20.1") }
    // dead mappings — baked constants, probed anyway for surprise updates
    p["mcp:1.7.10"] = listOf("stable_12")
    p["mcp:1.12.2"] = listOf("stable_39")
    Io.writeText(Io.path(out, "ProbedVersions.kt"), buildString {
        appendLine("package xyz.wagyourtail.unimined.init")
        appendLine()
        appendLine("/** Build-time probe cache — regenerated by")
        appendLine(" *  `genProbedVersions`, committed so binaries resolve")
        appendLine(" *  versions offline. Each list is newest-first; empty")
        appendLine(" *  list = probe failed at last generation. */")
        appendLine("object Probed {")
        appendLine("    val MAP = mapOf(")
        for ((k, vs) in p) {
            val lit = vs.joinToString(", ") { "\"$it\"" }
            appendLine("        \"$k\" to listOf($lit),")
        }
        appendLine("    )")
        appendLine("}")
    })
}
