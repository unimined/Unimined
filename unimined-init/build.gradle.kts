/**
 * Templates ship as plain files under `templates/` (NOT classpath
 * resources) — the codegen task below embeds them into commonMain
 * source so JVM and Native targets share one lookup without a
 * classpath.
 */
val genTemplateFiles by tasks.registering {
    val src = layout.projectDirectory.dir("templates")
    val out = layout.buildDirectory.dir(
        "generated/init-templates/xyz/wagyourtail/unimined/init")
    inputs.dir(src)
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.apply { deleteRecursively(); mkdirs() }
        val b64 = StringBuilder()
        val keys = StringBuilder()
        src.asFile.walkTopDown().filter { it.isFile }
            .sortedBy { it.relativeTo(src.asFile).invariantSeparatorsPath }
            .forEach { f ->
                val rel = "/templates/" + f.relativeTo(src.asFile)
                    .invariantSeparatorsPath
                b64.append("    \"$rel\" to \"")
                // java.util.Base64 here is fine — codegen runs on JVM
                b64.append(Base64.getEncoder()
                    .encodeToString(f.readBytes()))
                b64.append("\",\n")
                keys.append("    \"$rel\",\n")
            }
        dir.resolve("TemplateFiles.kt").writeText("""
            |package xyz.wagyourtail.unimined.init
            |
            |import kotlin.io.encoding.Base64
            |import kotlin.io.encoding.ExperimentalEncodingApi
            |
            |/** Embedded template assets — generated by `genTemplateFiles`, do not edit. */
            |@OptIn(ExperimentalEncodingApi::class)
            |internal object TemplateFiles {
            |    private val FILES = mapOf(
            |$b64    )
            |    fun exists(path: String): Boolean = FILES.containsKey(path)
            |    operator fun get(path: String): ByteArray =
            |        FILES[path]?.let { Base64.decode(it) }
            |            ?: error("no embedded template '${'$'}path'")
            |    fun names(): Set<String> = FILES.keys
            |}
            |""".trimMargin())
    }
}

