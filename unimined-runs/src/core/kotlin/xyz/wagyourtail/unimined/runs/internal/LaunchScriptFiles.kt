package xyz.wagyourtail.unimined.runs.internal

import java.io.File

/**
 * Renders runnable `.sh`/`.cmd` launch scripts from a fully-resolved
 * launch — the MDG `createLaunchScripts` parity surface. Gradle-free:
 * everything arrives as plain strings so the renderer is unit-testable
 * and usable from both the run task's script mode and external tools.
 */
internal object LaunchScriptFiles {

    /** A fully-resolved launch — same inputs `MinecraftRunTask` execs. */
    data class Launch(
        /** `java` binary (resolved launcher path or plain `java`). */
        val javaExecutable: String,
        val mainClass: String,
        /** Ordered classpath entries (absolute paths). */
        val classpath: List<String>,
        /** JVM args as they precede `-cp`. */
        val jvmArgs: List<String>,
        /** Program args after the main class. */
        val programArgs: List<String>,
        /** Process environment overrides. */
        val environment: Map<String, String>,
    )

    /** POSIX quoting — always double-quoted so spaces survive; `\ " $
     *  and backticks escaped for double-quote context. */
    private fun shQuote(s: String): String =
        "\"" + s.replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("$", "\\$")
            .replace("`", "\\`") + "\""

    /** cmd.exe quoting — no escape convention exists; bare wrap and
     *  rely on args being path/simple values. */
    private fun cmdQuote(s: String): String = "\"$s\""

    fun renderSh(launch: Launch): String = buildString {
        append("#!/bin/sh\n")
        append("# Generated by unimined — launches Minecraft outside Gradle.\n")
        append("# Regenerate via the env's genLaunchScript<Name> task.\n")
        append("cd \"$(dirname \"$0\")\" || exit 1\n")
        for ((k, v) in launch.environment) {
            append("export $k=${shQuote(v)}\n")
        }
        append("exec ${shQuote(launch.javaExecutable)}")
        launch.jvmArgs.forEach { append(" ${shQuote(it)}") }
        append(" -cp ${shQuote(launch.classpath.joinToString(":"))}")
        append(" ${shQuote(launch.mainClass)}")
        launch.programArgs.forEach { append(" ${shQuote(it)}") }
        append("\n")
    }

    fun renderCmd(launch: Launch): String = buildString {
        append("@echo off\r\n")
        append("rem Generated by unimined — launches Minecraft outside Gradle.\r\n")
        append("cd /d \"%~dp0\"\r\n")
        for ((k, v) in launch.environment) {
            append("set \"$k=$v\"\r\n")
        }
        append(cmdQuote(launch.javaExecutable))
        launch.jvmArgs.forEach { append(" ${cmdQuote(it)}") }
        append(" -cp ${cmdQuote(launch.classpath.joinToString(";"))}")
        append(" ${cmdQuote(launch.mainClass)}")
        launch.programArgs.forEach { append(" ${cmdQuote(it)}") }
        append("\r\n")
    }

    /** Write `<baseName>.sh` (executable) and `<baseName>.cmd` into
     *  [dir]; returns both files. */
    fun write(dir: File, baseName: String, launch: Launch): List<File> {
        dir.mkdirs()
        val sh = File(dir, "$baseName.sh").apply {
            writeText(renderSh(launch))
            setExecutable(true, false)
        }
        val cmd = File(dir, "$baseName.cmd").apply {
            writeText(renderCmd(launch))
        }
        return listOf(sh, cmd)
    }
}
