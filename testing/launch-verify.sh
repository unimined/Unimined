#!/bin/bash
# Launch-verify harness — Phase D regression gate.
# Usage: launch-verify.sh <fixture-dir> <gradle-task> <timeout-sec> <success-regex> [extra-fail-regex]
#
# Runs `./gradlew <task>` in <fixture-dir>, polls the newest log under run/
# for <success-regex> (extended grep). On success: SIGTERMs the game JVM
# (exit 143 = clean stop, expected). Fails fast on BUILD FAILED / crash
# reports / fatal exceptions. Prints a VERIFIED/FAIL verdict + evidence.
#
# Env: DISPLAY is inherited — pass through `xvfb-run` for headless
# clients. GLX needs a 24-bit screen (the depth-8 default crashes
# LWJGL at glClear with BadDrawable):
#   xvfb-run -a -s "-screen 0 1280x720x24" ./launch-verify.sh ...
#
# Fixtures are generated by unimined-cli (see .github/workflows/
# config-cache.yml for the invocation shape). ModLoader-era games log
# to ModLoader.txt — newest_log() covers it alongside *.log.
# Stale logs/crash reports under run/ poison verdicts — clean them
# between attempts.

FIXTURE="$1"; TASK="$2"; TIMEOUT="${3:-240}"; SUCCESS_RE="$4"; FAIL_RE="$5"
cd "$FIXTURE" || { echo "FAIL: no fixture dir $FIXTURE"; exit 2; }

LOGROOT="$FIXTURE/run"
BASELINE=$(mktemp)
# snapshot existing crash reports so only NEW ones count
find "$LOGROOT" -name "crash-*.txt" 2>/dev/null > "$BASELINE"

# per-fixture gradle output — parallel invocations must not clobber
# each other's failure evidence
GOUT=$(mktemp /tmp/lv-gradle-XXXXXX.out)
./gradlew "$TASK" > "$GOUT" 2>&1 &
GPID=$!

deadline=$(( $(date +%s) + TIMEOUT ))
verdict=""
evidence=""

newest_log() {
    find "$LOGROOT" \( -name "*.log" -o -name "ModLoader.txt" \) -type f 2>/dev/null -printf "%T@ %p\n" | sort -n | tail -1 | cut -d' ' -f2-
}

while [ -z "$verdict" ] && [ "$(date +%s)" -lt "$deadline" ]; do
    # gradle-level failure
    if ! kill -0 $GPID 2>/dev/null; then
        wait $GPID; rc=$?
        if grep -q "BUILD FAILED" $GOUT; then
            verdict="FAIL(gradle)"; evidence=$(grep -m3 -E "FAILURE|Exception|error:" $GOUT | tr '\n' '|')
        else
            # task ended on its own (e.g. server that exits) — check log for success anyway
            L=$(newest_log)
            if [ -n "$L" ] && grep -qE "$SUCCESS_RE" "$L"; then
                verdict="VERIFIED"; evidence="task exited; matched in $(basename "$L")"
            else
                verdict="FAIL(exit=$rc)"; evidence="task ended w/o success marker; $(tail -3 $GOUT | tr '\n' '|')"
            fi
        fi
        break
    fi

    L=$(newest_log)
    if [ -n "$L" ]; then
        if grep -qE "$SUCCESS_RE" "$L" 2>/dev/null; then
            verdict="VERIFIED"; evidence="$(grep -m2 -E "$SUCCESS_RE" "$L" | tr '\n' '|') @ $(basename "$L")"
            break
        fi
        if [ -n "$FAIL_RE" ] && grep -qE "$FAIL_RE" "$L" 2>/dev/null; then
            verdict="FAIL(log)"; evidence="$(grep -m2 -E "$FAIL_RE" "$L" | tr '\n' '|') @ $(basename "$L")"
            break
        fi
    fi

    # new crash report = hard fail
    newcrash=$(find "$LOGROOT" -name "crash-*.txt" -type f 2>/dev/null | grep -vxF -f "$BASELINE" | head -1)
    if [ -n "$newcrash" ]; then
        verdict="FAIL(crash-report)"; evidence="$newcrash: $(grep -m2 -E "Description|Exception|Error" "$newcrash" | tr '\n' '|')"
        break
    fi
    sleep 3
done
[ -z "$verdict" ] && { verdict="FAIL(timeout)"; L=$(newest_log); evidence="no success marker in ${TIMEOUT}s; last log: ${L:-none}"; }

# stop the game JVM (clean stop -> exit 143 on the java proc is fine)
# pattern anchored on the java binary — the harness's own argv also
# carries $FIXTURE, an unanchored -f would self-terminate
pkill -TERM -f "^[^ ]*java .*$FIXTURE" 2>/dev/null
kill -TERM $GPID 2>/dev/null
sleep 2
pkill -9 -f "^[^ ]*java .*$FIXTURE" 2>/dev/null
kill -9 $GPID 2>/dev/null
wait $GPID 2>/dev/null

echo "[$verdict] $FIXTURE $TASK"
echo "  evidence: $evidence"
[ "${verdict#VERIFIED}" = "$verdict" ] && { echo "  --- gradle tail ---"; tail -8 $GOUT; }
rm -f "$BASELINE"
[ "${verdict#VERIFIED}" = "$verdict" ]
